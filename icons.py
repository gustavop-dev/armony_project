def _svg(nombre, color, grosor=1.5):
    trazos = "".join(
        f'<path stroke-linecap="round" stroke-linejoin="round" d="{d}"/>'
        for d in PATHS[nombre]
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="{grosor}">{trazos}</svg>'
    ).encode("utf-8")


def _screen_dpr():
    """Escalado real de la pantalla (1.0, 1.25, 1.5, 2.0...) para nitidez correcta."""
    app = QtGui.QGuiApplication.instance()
    if app is not None:
        scr = app.primaryScreen()
        if scr is not None:
            return max(1.0, float(scr.devicePixelRatio()))
    return 2.0


def pixmap(nombre, color, px=16, grosor=1.5):
    """QPixmap del icono, nitido y con tamano LOGICO exactamente px.

    Se renderiza a la resolucion fisica real de la pantalla y se marca su
    devicePixelRatio, para que Qt lo muestre siempre a px logicos sin desbordarse.
    """
    dpr = _screen_dpr()
    fisico = max(1, round(px * dpr))
    r = QtSvg.QSvgRenderer(QtCore.QByteArray(_svg(nombre, color, grosor)))
    pm = QtGui.QPixmap(fisico, fisico)
    pm.setDevicePixelRatio(dpr)
    pm.fill(QtCore.Qt.transparent)
    p = QtGui.QPainter(pm)
    # Destino explicito en px logicos: sin el, el SVG ocupa el pixmap en px
    # FISICOS y con escalado (125 %, 150 %...) sale mas grande y recortado.
    r.render(p, QtCore.QRectF(0, 0, px, px))
    p.end()
    return pm


def save_png(nombre, color, px, path, grosor=1.8):
    """Guarda un icono como PNG (para usarlo en QSS, p. ej. la flecha del combo)."""
    r = QtSvg.QSvgRenderer(QtCore.QByteArray(_svg(nombre, color, grosor)))
    pm = QtGui.QPixmap(px, px)
    pm.fill(QtCore.Qt.transparent)
    p = QtGui.QPainter(pm)
    r.render(p)
    p.end()
    pm.save(path, "PNG")
    return path


def label(nombre, color, px=16, grosor=1.5):
    """QLabel con el icono, de tamano fijo px y ajustado a ese hueco (nunca desborda)."""
    from PySide6 import QtWidgets
    lab = QtWidgets.QLabel()
    lab.setFixedSize(px, px)
    lab.setScaledContents(True)     # el pixmap se ajusta exactamente a px x px
    lab.setPixmap(pixmap(nombre, color, px, grosor))
    lab.setStyleSheet("background: transparent; border: none;")
    return lab
